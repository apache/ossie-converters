"""Generate the Tableau converter docs/loss-catalog.md and docs/expression-mapping.md.

`--check` exits 1 if a file is out of date."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import sqlglot  # noqa: E402
from ossie_tableau.losses import CATALOG  # noqa: E402
from ossie_tableau.calc_catalog import CATALOG as CALCS, for_dialect  # noqa: E402

OUT = ROOT / "docs/loss-catalog.md"
OUT_EXPR = ROOT / "docs/expression-mapping.md"


def render() -> str:
    lines = [
        "# Loss catalogue",
        "",
        "Generated by `tools/gen_docs.py` from `ossie_tableau/losses.py`; do not edit by hand.",
        "",
        "Categories: `preserved` (stashed and re-emitted, so the round trip is lossless), `parked` (stashed and restorable), `approximated` (close but not identical), `dropped` (only the loss record remains).",
        "Severities: `info`, `warning`, `error` (`--strict` fails on `error`).",
        "",
        "| Kind | Category | Severity | Remedy |",
        "|---|---|---|---|",
    ]
    for kind, s in CATALOG.items():
        lines.append(f"| `{kind}` | {s.category} | {s.severity} | {s.remedy.replace('|', '/')} |")
    return "\n".join(lines) + "\n"


def render_expr() -> str:
    lines = [
        "# Expression mapping",
        "",
        "Generated by `tools/gen_docs.py` from `ossie_tableau/calc_catalog.py`; do not edit by hand.",
        "",
        "Status: `direct` (same result in both engines), `approximated` (close, see note), `unmappable` (never translated; reported as a loss).",
        "",
        "| Tableau | Arity | Snowflake SQL template | Status | Result | Note |",
        "|---|---|---|---|---|---|",
    ]
    for e in CALCS:
        ar = "/".join(str(a) for a in e.arity)
        sql = (e.sql or "").replace("|", "/")
        lines.append(f"| `{e.name}` | {ar} | `{sql}` | {e.status} | {e.result} | {e.note.replace('|', '/')} |")
    lines += [
        "",
        "## BigQuery",
        "",
        "BigQuery uses its own template where one is written; otherwise the Snowflake template above, when it is known to transpile unchanged. Anything else is `unmappable` (never guessed).",
        "",
        "| Tableau | BigQuery SQL template | Status | Note |",
        "|---|---|---|---|",
    ]
    for e in CALCS:
        b = for_dialect(e, "bigquery")
        bsql = sqlglot.transpile(b.sql, read="snowflake", write="bigquery")[0] if b.sql and b.sql_dialect == "snowflake" else b.sql
        lines.append(f"| `{e.name}` | `{(bsql or '').replace('|', '/')}` | {b.status} | {b.note.replace('|', '/')} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    targets = [(OUT, render()), (OUT_EXPR, render_expr())]
    if "--check" in sys.argv:
        return 0 if all(p.exists() and p.read_text() == t for p, t in targets) else 1
    for p, t in targets:
        p.parent.mkdir(exist_ok=True)
        p.write_text(t)
    return 0


if __name__ == "__main__":
    sys.exit(main())
