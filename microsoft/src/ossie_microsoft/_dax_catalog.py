"""Every DAX function, classified, so the translator refuses each one for a stated reason.

``_dax_to_sql`` translates a deliberately small set of DAX constructs. For everything
else it must say *why* it refused, and a generic "not supported" is not good enough: the
reason tells a reader whether a measure is waiting on a later tier of this converter, on
a feature the Apache Ossie specification does not define yet, or will never have a
portable form. This module is that classification, one entry per DAX function.

Each entry is ``NAME: (tier, verdict)``.

Tiers (what kind of construct the function is):

* ``T0`` scalar, row level
* ``T1`` aggregate, including the X iterators
* ``T2`` filtered aggregate (``CALCULATE`` / ``KEEPFILTERS`` with predicates)
* ``T3`` composition (measure references, ``VAR``)
* ``T4`` time intelligence, windows, semi-additive
* ``T5`` filter context, changed or inspected (``ALL``, ``REMOVEFILTERS``, ``ISFILTERED``, ...)
* ``T6`` table expressions (a calculated table, or a table argument)
* ``T7`` not part of a portable semantic model (visual calculations, calculation groups,
  user/session functions, metadata)

Verdicts (what the target can express):

* ``PORTABLE`` exact 1:1 in ``OSSIE_SQL_2026``
* ``PORTABLE+RULE`` exact in ``OSSIE_SQL_2026`` through a deterministic rewrite
* ``EXTENDED-SQL`` exact only in a SQL dialect richer than ``OSSIE_SQL_2026``
* ``QUERY`` exact only as a SQL query (a calculated-table source), not as an expression
* ``SPEC-GAP(x)`` exact only once the specification defines feature *x*
* ``REFUSE`` no faithful portable form
* ``N/A`` not a semantic-model construct

A ``PORTABLE`` verdict means a faithful translation exists, not that this converter
emits it yet; the functions emitted today are listed in ``_dax_to_sql``. Verdicts are a
design classification checked against ``core-spec/expression_language.md``; a function
is only translated once it has golden tests, and where a function's DAX semantics
differ from SQL the translator refuses it whatever its verdict here (``COUNT`` and
``DISTINCTCOUNT`` are the current examples).
"""

